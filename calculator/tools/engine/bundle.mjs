// Bundle src/engine/**/*.mjs into src/engine/engine.bundle.js: one self-contained factory function
// (each module in its own scope, imports resolved), so the page can embed it in its engine module and also start
// it inside a Web Worker. Run: node tools/engine/bundle.mjs   (build_time_series.py runs it when sources change)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../src/engine');
export function sourceHash() {
  const files = []; const walk = d => { for (const f of readdirSync(d).sort()) { const p = path.join(d, f); if (statSync(p).isDirectory()) walk(p); else if (f.endsWith('.mjs')) files.push(p); } }; walk(root);
  const h = createHash('sha256'); for (const f of files) { h.update(path.relative(root, f)); h.update(readFileSync(f)); } return h.digest('hex').slice(0, 16);
}
const IMPORT_RE = /^import\s+(?:([\s\S]*?)\s+from\s+)?'([^']+)';?[ \t]*$/gm;
async function main() {
  const order = [], seen = new Set();
  const visit = rel => {
    if (seen.has(rel)) return; seen.add(rel);
    const src = readFileSync(path.join(root, rel), 'utf8');
    for (const m of src.matchAll(IMPORT_RE)) visit(path.normalize(path.join(path.dirname(rel), m[2])).replace(/\\/g, '/'));
    order.push(rel);
  };
  visit('index.mjs');
  const parts = [];
  for (const rel of order) {
    let src = readFileSync(path.join(root, rel), 'utf8');
    const exportsOf = Object.keys(await import(pathToFileURL(path.join(root, rel)).href));
    src = src.replace(IMPORT_RE, (all, spec, from) => {
      const target = JSON.stringify(path.normalize(path.join(path.dirname(rel), from)).replace(/\\/g, '/'));
      if (!spec) return '';
      spec = spec.trim();
      const ns = /^\*\s+as\s+(\w+)$/.exec(spec); if (ns) return 'const ' + ns[1] + ' = __m[' + target + '];';
      const named = /^\{([\s\S]*)\}$/.exec(spec); if (named) return 'const { ' + named[1].split(',').map(s => s.trim()).filter(Boolean).map(s => s.replace(/\s+as\s+/, ': ')).join(', ') + ' } = __m[' + target + '];';
      throw new Error('Unsupported import in ' + rel + ': ' + all);
    });
    src = src.replace(/^export\s+\{[^}]*\};?[ \t]*$/gm, '').replace(/^export\s+(?=(async\s+)?(function|const|let|var|class)\b)/gm, '');
    if (/^export\s/m.test(src)) throw new Error('Unsupported export form in ' + rel);
    parts.push('__m[' + JSON.stringify(rel) + '] = (function () {\n' + src + '\nreturn { ' + exportsOf.join(', ') + ' };\n})();');
  }
  const hash = sourceHash();
  const out = '// GENERATED by tools/engine/bundle.mjs from src/engine (source hash ' + hash + ') — do not edit.\n' +
    'const GMEngineFactory = function () {\n"use strict";\nconst __m = {};\n' + parts.join('\n') + '\nreturn __m["index.mjs"];\n};\n';
  writeFileSync(path.join(root, 'engine.bundle.js'), out);
  // smoke test: the bundle evaluates and runs a trivial analysis
  const f = new Function(out + '\nreturn GMEngineFactory();')();
  const r = f.gmRun({ id: 'summary_t1', alpha: 0.05, options: { inputMode: 'summary', mean1: 1, sd1: 1, n1: 10, null: 0 }, fields: {}, data: {} });
  if (r.error || !r.tables.length) throw new Error('bundle smoke test failed: ' + JSON.stringify(r).slice(0, 300));
  console.log('engine.bundle.js written (' + (out.length / 1024).toFixed(0) + ' KB, ' + order.length + ' modules, hash ' + hash + ')');
}
if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
