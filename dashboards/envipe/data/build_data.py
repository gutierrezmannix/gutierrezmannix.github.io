#!/usr/bin/env python3
"""
Wrap the ENVIPE CSVs produced by envipe_dashboard_build.do into JavaScript
files the dashboard loads with <script> tags.

Why: a page opened straight from disk (file://) cannot fetch() a CSV, but it
can load a .js file. Wrapping the CSV text this way keeps the dashboard
working with no internet connection and no web server.

Input  (this folder):
    envipe_agg_part*.csv   states + national, all adults
    envipe_grp_part*.csv   states + national, by gender and age group
    envipe_mun_part*.csv   municipalities
    envipe_aum_part*.csv   urban areas
    envipe_catalog.csv, envipe_value_labels.csv,
    envipe_municipios.csv, envipe_areas.csv, envipe_settings.csv

Output (this folder):
    envipe-meta.js                        catalog, labels, lookups, part counts
    envipe-part1.js, envipe-part2.js ...  all adults (loaded at start)
    envipe-grp1.js ..., envipe-mun1.js ..., envipe-aum1.js ...
                                          loaded only when the view needs them

Run:   python3 build_data.py
(The GitHub Action in .github/workflows/envipe-data.yml runs this
automatically whenever the CSVs in this folder change.)

Standard library only.
"""
import glob
import json
import os
import re
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))

# CSV prefix -> (output js prefix, how the js registers itself)
SETS = {
    "agg": "envipe-part",
    "grp": "envipe-grp",
    "mun": "envipe-mun",
    "aum": "envipe-aum",
}


def read_text(path):
    """Read a CSV as UTF-8. Bytes that are not valid UTF-8 (e.g. a label cut in
    the middle of an accented letter) are dropped instead of breaking the page."""
    if not os.path.exists(path):
        return ""
    with open(path, "rb") as f:
        raw = f.read()
    text = raw.decode("utf-8", errors="ignore")
    return text.replace("\r\n", "\n").replace("\r", "\n").strip() + "\n"


def part_number(path):
    m = re.search(r"part(\d+)\.csv$", path)
    return int(m.group(1)) if m else 0


def main():
    counts = {}
    for key, js_prefix in SETS.items():
        parts = sorted(glob.glob(os.path.join(HERE, "envipe_%s_part*.csv" % key)), key=part_number)
        # Remove js files left over from an earlier build with more parts
        for old in glob.glob(os.path.join(HERE, js_prefix + "[0-9]*.js")):
            os.remove(old)
        for p in parts:
            k = part_number(p)
            text = read_text(p)
            out = os.path.join(HERE, "%s%d.js" % (js_prefix, k))
            with open(out, "w", encoding="utf-8") as f:
                f.write("/* Generated by build_data.py from %s. Do not edit. */\n" % os.path.basename(p))
                if key == "agg":
                    # the all-adults parts keep the original format
                    f.write("(window.ENVIPE_PARTS = window.ENVIPE_PARTS || []).push(")
                    f.write(json.dumps(text, ensure_ascii=False))
                    f.write(");\n")
                else:
                    f.write("(window.ENVIPE_SETS = window.ENVIPE_SETS || {})[%s] = " % json.dumps("%s%d" % (key, k)))
                    f.write(json.dumps(text, ensure_ascii=False))
                    f.write(";\n")
            print("wrote", os.path.basename(out), "(%.1f MB)" % (os.path.getsize(out) / 1e6))
        counts[key] = len(parts)

    if not counts["agg"]:
        raise SystemExit("No envipe_agg_part*.csv files found in " + HERE)

    meta = {
        "built": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "parts": counts["agg"],
        "sets": counts,
        "catalog": read_text(os.path.join(HERE, "envipe_catalog.csv")),
        "labels": read_text(os.path.join(HERE, "envipe_value_labels.csv")),
        "municipios": read_text(os.path.join(HERE, "envipe_municipios.csv")),
        "areas": read_text(os.path.join(HERE, "envipe_areas.csv")),
        "settings": read_text(os.path.join(HERE, "envipe_settings.csv")),
    }
    out = os.path.join(HERE, "envipe-meta.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by build_data.py. Do not edit. */\n")
        f.write("window.ENVIPE_META = ")
        f.write(json.dumps(meta, ensure_ascii=False))
        f.write(";\n")
    print("wrote envipe-meta.js", counts)


if __name__ == "__main__":
    main()
